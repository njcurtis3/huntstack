"""
Build apps/api/src/data/places.ts: towns that name hunting areas on Where to Hunt.

Sources (US Census Bureau, public domain), downloaded by hand:
  2024 Gazetteer places   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_place_national.zip
  2023 population (city)  https://www2.census.gov/programs-surveys/popest/datasets/2020-2023/cities/totals/sub-est2023.csv

Usage:
  python -I scripts/build-places.py <2024_Gaz_place_national.txt> <sub-est2023.csv>

Each place: name (without "city"/"town"/"CDP"), state, county (the county holding most of an
incorporated place's people; none for census-designated places, which have no estimate),
population (0 for CDPs), and its internal point. Only the states HuntStack covers.
"""

import csv
import json
import io
import re
import sys
from pathlib import Path

REGISTRY = Path(__file__).resolve().parent.parent / "packages" / "shared" / "src" / "states.json"
# The covered states, from the state registry
STATES = {s["code"] for s in json.loads(REGISTRY.read_text(encoding="utf-8"))["states"] if s["covered"]}
# Census state FIPS codes, all states; only the covered ones are kept
ALL_FIPS = {
    "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC",
    "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
    "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT",
    "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
    "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT",
    "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY",
}
FIPS = {f: st for f, st in ALL_FIPS.items() if st in STATES}

# The Gazetteer's NAME ends in its legal description: "Stuttgart city", "Hayti Heights town".
# Removed once, in lower case only: "Kansas City city" is Kansas City (until 2026-11-21 the
# suffix was removed repeatedly and ignoring case, which left "Kansas" and "Oklahoma")
SUFFIX = re.compile(
    r"\s+(city|town|village|CDP|borough|municipality|city and borough|metropolitan government"
    r"|unified government|consolidated government|\(balance\))(\s+\(balance\))?$",
)

OUT = Path(__file__).resolve().parent.parent / "apps" / "api" / "src" / "data" / "places.ts"


def clean(name: str) -> str:
    return SUFFIX.sub("", name).strip()


def main(gaz_path: str, est_path: str) -> None:
    # Population and county for incorporated places
    pop: dict[str, int] = {}
    county_name: dict[str, str] = {}
    best_part: dict[str, tuple[int, str]] = {}
    with open(est_path, encoding="latin-1", newline="") as f:
        for r in csv.DictReader(f):
            st = FIPS.get(r["STATE"])
            if not st:
                continue
            p = int(r["POPESTIMATE2023"] or 0)
            if r["SUMLEV"] == "050":
                county_name[r["STATE"] + r["COUNTY"]] = r["NAME"]
            elif r["SUMLEV"] == "162":
                pop[r["STATE"] + r["PLACE"]] = p
            elif r["SUMLEV"] == "157":
                key = r["STATE"] + r["PLACE"]
                if p > best_part.get(key, (-1, ""))[0]:
                    best_part[key] = (p, r["STATE"] + r["COUNTY"])

    rows = []
    with open(gaz_path, encoding="utf-8", newline="") as f:
        text = f.read()
    for r in csv.DictReader(io.StringIO(text), delimiter="\t"):
        r = {k.strip(): (v or "").strip() for k, v in r.items()}
        if r["USPS"] not in STATES:
            continue
        geoid = r["GEOID"]
        county = county_name.get(best_part.get(geoid, (0, ""))[1], "")
        rows.append((
            clean(r["NAME"]), r["USPS"], county, pop.get(geoid, 0),
            round(float(r["INTPTLAT"]), 4), round(float(r["INTPTLONG"]), 4),
        ))
    rows.sort(key=lambda x: (x[1], x[0]))

    def q(s: str) -> str:
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"

    lines = [
        "// Generated by scripts/build-places.py from US Census Bureau data (public domain):",
        "// 2024 Gazetteer places and 2023 city population estimates. Do not edit by hand.",
        "// [name, state, county ('' for census-designated places), population (0 for CDPs), lat, lng]",
        "",
        "export type Place = readonly [name: string, state: string, county: string, population: number, lat: number, lng: number]",
        "",
        "export const PLACES: readonly Place[] = [",
    ]
    lines += [f"  [{q(n)}, {q(s)}, {q(c)}, {p}, {la}, {lo}]," for n, s, c, p, la, lo in rows]
    lines += ["]", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} places to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
