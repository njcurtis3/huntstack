"""Copy the Map's waterfowl zone shapes into the API, so Where to Hunt knows each area's zone.

    python -I scripts/build-api-zones.py

Reads apps/web/public/data/waterfowl-zones-2026.json (built by scripts/zones/build-zones.mjs)
and writes apps/api/src/data/zones.ts: per shape its id, state, the season zone names that
apply there (duckUnits + gooseUnits, as stored in seasons.units) and its rings. Run it again
whenever the zone file is rebuilt, and commit both files.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'apps/web/public/data/waterfowl-zones-2026.json'
OUT = ROOT / 'apps/api/src/data/zones.ts'


def ring(r):
    return [[round(x, 4), round(y, 4)] for x, y in r]


def main():
    data = json.loads(SRC.read_text(encoding='utf-8'))
    shapes = []
    for f in data['features']:
        p, g = f['properties'], f['geometry']
        polys = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']
        units = list(dict.fromkeys([*p.get('duckUnits', []), *p.get('gooseUnits', [])]))
        shapes.append([p['id'], p['state'], units, [[ring(r) for r in poly] for poly in polys]])
    body = json.dumps(shapes, separators=(',', ':'), ensure_ascii=False)
    OUT.write_text(
        '// GENERATED by scripts/build-api-zones.py from apps/web/public/data/waterfowl-zones-2026.json.\n'
        '// Do not edit by hand. [id, state, season zone names (seasons.units), polygons: rings of [lng, lat]]\n'
        'export type ZoneShape = [string, string, string[], number[][][][]]\n\n'
        f'export const ZONE_SHAPES: ZoneShape[] = {body}\n',
        encoding='utf-8',
    )
    print(f'{len(shapes)} shapes -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
